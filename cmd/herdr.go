// Herdr plugin event names and the environment variables herdr sets when it
// runs an event hook. See https://herdr.dev/docs/socket-api/#plugin-apis.
const (
	herdrEventEnv        = "HERDR_PLUGIN_EVENT_JSON"
	herdrEventCreated    = "worktree_created"
	herdrEventRemoved    = "worktree_removed"
	herdrRemoveTimeout   = 5 * time.Minute
	herdrPluginID        = "wt"
	herdrManifestName    = "herdr-plugin.toml"
	herdrMinVersion      = "0.9.0"
	herdrPluginDirEnvVar = "WT_HERDR_PLUGIN_DIR"
	herdrStateDirEnv     = "HERDR_PLUGIN_STATE_DIR"
	herdrSetupKillWait   = 5 * time.Second
)

// herdrEvent mirrors the JSON herdr places in HERDR_PLUGIN_EVENT_JSON for
// worktree.* events. Only the fields wt needs are declared.
type herdrEvent struct {
	Event string `json:"event"`
	Data  struct {
		Workspace struct {
			WorkspaceID string `json:"workspace_id"`
			Worktree    struct {
				RepoKey      string `json:"repo_key"` // shared git dir (e.g. /proj/.bare or /proj/.git)
				RepoName     string `json:"repo_name"`
				RepoRoot     string `json:"repo_root"` // main checkout herdr resolved the repo from
				CheckoutPath string `json:"checkout_path"`
			} `json:"worktree"`
		} `json:"workspace"`
		Worktree struct {
			Path   string `json:"path"`
			Branch string `json:"branch"`
			IsBare bool   `json:"is_bare"`
		} `json:"worktree"`
		Forced bool `json:"forced"`
	} `json:"data"`
}

func newHerdrCmd() *cobra.Command {
	cmd := &cobra.Command{
		Use:   "herdr",
		Short: "Herdr integration",
		Long: `Commands for integrating wt with herdr (https://herdr.dev).

Herdr owns worktree creation and removal. The wt plugin hooks into herdr's
worktree.created and worktree.removed events to apply shared files and run
setup/teardown hooks from .worktree.yml, so worktrees created from herdr's
sidebar behave like ones created with 'wt add'.`,
	}

	cmd.AddCommand(newHerdrInitCmd())
	cmd.AddCommand(newHerdrHookCreatedCmd())
	cmd.AddCommand(newHerdrHookRemovedCmd())

	return cmd
}

func newHerdrInitCmd() *cobra.Command {
	cmd := &cobra.Command{
		Use:   "init",
		Short: "Install the wt plugin into herdr",
		Long: `Writes the wt herdr plugin manifest and links it with 'herdr plugin link'.

The plugin is global to herdr, not per project: it fires for every worktree
herdr creates or removes and does nothing for repos without a .worktree.yml.
Run this once per machine.`,
		Args: cobra.NoArgs,
		RunE: runHerdrInit,
	}
	cmd.Flags().String("binary", "", "Path to the wt binary herdr should run (default: this executable)")
	cmd.Flags().Bool("no-link", false, "Write the manifest but do not run 'herdr plugin link'")
	return cmd
}

